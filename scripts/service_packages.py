"""Generate small service packaging projects; runtime source stays in src/."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVICES = {
    "suno": ("suno", "Suno", "Music"),
    "seedance": ("seedance", "Seedance", "Clapperboard"),
    "happyhorse": ("happy_horse", "HappyHorse", "Clapperboard"),
    "gpt-image": ("gpt_image", "GPT Image", "Image"),
    "nano-banana": ("nano_banana", "Nano Banana", "Image"),
}
SERVICE_ROUTES = {
    "suno": ("/suno/audios", "/suno/tasks"),
    "seedance": ("/seedance/videos", "/seedance/tasks"),
    "happyhorse": ("/happyhorse/videos", "/happyhorse/tasks"),
    "gpt-image": ("/openai/images/generations", "/openai/tasks"),
    "nano-banana": ("/nano-banana/images", "/nano-banana/tasks"),
}


def generated_files() -> dict[Path, str]:
    """Return reproducible metadata and hook copies for the five projects."""
    version = json.loads((ROOT / "src/lfx_acedatacloud/extension.json").read_text())[
        "version"
    ]
    files = {}
    for slug, (key, label, icon) in SERVICES.items():
        module = f"lfx_acedatacloud_{key}"
        distribution = f"lfx-acedatacloud-{slug}"
        bundle = f"ace_{key}"
        display = f"{label} by Ace Data Cloud"
        directory = ROOT / "packages" / slug
        attribution = (
            "utm_source=opensource&utm_medium=referral&utm_campaign=evergreen"
            f"&utm_content=langflow_{slug.replace('-', '_')}_package"
        )
        platform = "https://platform.acedata.cloud"
        guide = slug if slug != "happyhorse" else "happy-horse"
        source = "https://github.com/AceDataCloud/LangflowAceDataCloud"
        wheel = f"lfx_acedatacloud_{slug.replace('-', '_')}-{version}-py3-none-any.whl"
        wheel_url = f"{source}/releases/download/v{version}/{wheel}"
        generation_route, task_route = SERVICE_ROUTES[slug]
        files[
            directory / "pyproject.toml"
        ] = f'''# Generated by scripts/service_packages.py; edit the generator.
[build-system]
requires = ["hatchling>=1.31,<2"]
build-backend = "hatchling.build"

[project]
name = "{distribution}"
version = "{version}"
description = "{display}: generation and same-task retrieval for Langflow"
readme = "README.md"
requires-python = ">=3.10,<3.15"
license = "MIT"
authors = [{{name = "Ace Data Cloud", email = "dev@acedata.cloud"}}]
keywords = ["langflow", "lfx", "{slug}", "acedatacloud"]
dependencies = ["lfx>=1.12.5,<2", "httpx>=0.24,<1"]

[project.urls]
Homepage = "{platform}?{attribution}_homepage"
Documentation = "{source}/blob/v{version}/guides/{guide}.md"
Repository = "https://github.com/AceDataCloud/LangflowAceDataCloud"

[project.entry-points."langflow.extensions"]
{distribution} = "{module}"

[tool.hatch.service]
key = "{key}"
module = "{module}"
bundle = "{bundle}"
display = "{display}"
icon = "{icon}"

[tool.hatch.build.hooks.custom]
path = "hatch_build.py"

[tool.hatch.build.targets.wheel]
bypass-selection = true
exclude = ["*"]

[tool.hatch.build.targets.sdist]
include = ["/pyproject.toml", "/README.md", "/LICENSE", "/hatch_build.py", "/src"]
'''
        files[directory / "hatch_build.py"] = (
            "# Generated from scripts/service_build_hook.py; do not edit.\n"
            + (ROOT / "scripts/service_build_hook.py").read_text()
        )
        files[directory / "LICENSE"] = (ROOT / "LICENSE").read_text()
        files[directory / "README.md"] = f"""# {display} for Langflow

Install just the {label} Generate and Retrieve Task nodes. This service package
does not install the full Ace bundle or register a chat model provider.
It uses the same reviewed client, request rules, and task implementation as the
aggregate package. Ace Data Cloud supplies this integration; service-owner
endorsement is not implied.

## 1. Install the nodes

Version {version}. Install the public GitHub wheel in the same Python environment
as Langflow (1.12.5 or later):

```bash
python -m pip install "{wheel_url}"
lfx extension list
langflow run
```

The [versioned GitHub release]({source}/releases/tag/v{version}) provides the wheel
and a self-contained source archive. No GitHub account is needed to install it.
If version {version} is listed on [PyPI](https://pypi.org/project/{distribution}/),
you can also run `python -m pip install "{distribution}=={version}"`.
Suno and Seedance project creation was temporarily rate-limited by PyPI at the
0.1.3 release; the direct wheel command above works independently of PyPI listing
availability. [Official Langflow default inclusion](https://github.com/langflow-ai/langflow/pull/15659)
remains under review.

Restart an existing server. Open **Components → {display}** or search **{label}**.

## 2. Create and copy your application API key

1. Register or sign in at [Ace Data Cloud → Applications]({platform}/console/applications?{attribution}_api_key).
   If there is no **General application**, choose **Initialize General Application**
   first, then open it. A general-application key uses your account's enabled
   services; a service-specific application key is limited to that service.
2. Copy the existing API Key with the copy icon, or choose **Manage Keys → Create**
   to make a dedicated key, for example `Langflow {label}`.
3. Set the key's expiration, usage limit and **Allowed APIs** as needed. If you
   restrict Allowed APIs, include both `{generation_route}` and `{task_route}`
   so Generate and Retrieve Task can both work. Click **Create**, return to the
   key list or application card, and copy the token.
4. Confirm {label} service access, [current price and balance]({platform}/models?{attribution}_pricing)
   before a paid run. Copy only the raw token, without `Bearer ` or quotes.
   Use an application API key, not an account-management token.

![Copy the API key or open Manage Keys](https://raw.githubusercontent.com/AceDataCloud/LangflowAceDataCloud/v{version}/_assets/tutorial/get-api-key-en.png)

![Create a dedicated application API key](https://raw.githubusercontent.com/AceDataCloud/LangflowAceDataCloud/v{version}/_assets/tutorial/create-api-key-en.png)

## 3. Save a private Credential in Langflow

Open **Settings → Global Variables → Add New**. Set **Type** to **Credential**,
**Name** to `ACEDATACLOUD_API_KEY`, paste the token into **Value**, and choose
**Save Variable**. On **both Generate and Retrieve Task**, click the globe icon
next to **Ace Data Cloud API key** and select `ACEDATACLOUD_API_KEY`.
Confirm the binding survives a reload. Keep the token out of prompts, screenshots
and exported flow JSON; inspect exports for literal secrets before sharing.
Revoke a temporary or exposed key under **Manage Keys**, then update the saved
Credential if you replace it.

![Create a Credential before entering a key](https://raw.githubusercontent.com/AceDataCloud/LangflowAceDataCloud/v{version}/_assets/tutorial/17-create-credential.png)

## 4. Run and check the result

Generate submits once; Retrieve Task only queries the original task. API usage
is paid according to current service prices; installing this extension is free.
Use the retrieve-only flow with the original task ID while a task is pending;
do not rerun Generate just to check progress. Compare the task or trace with
[Usage History]({platform}/console/usages?{attribution}_usage). Charges are in Credits.
See the [English guide]({source}/blob/v{version}/guides/{guide}.md)
and [Chinese guide]({source}/blob/v{version}/guides/{guide}_zh_CN.md)
for first-run inputs and troubleshooting. For 401/403, check the copied key,
expiry, limits, both allowed routes, service access and balance.

## Packaging and saved flows

The wheel includes no-key generation and retrieve-only flow JSON under
`{module}/examples/`; use these with this service package. Aggregate examples
retain `ext:ace_data_cloud:*` IDs and require the aggregate installation.
This package uses `ext:{bundle}:<Class>@official` IDs. All five service packages
can coexist. With the aggregate installed, its legacy category remains alongside
the service category; neither replaces the other's saved nodes. Uninstalling
one package does not remove another package's files.

From the complete `v{version}` source checkout, build a wheel and a self-contained sdist with `python -m build packages/{slug}`. A local source install is `python -m pip install ./packages/{slug}`.
The shared hook stages runtime source under the unique `{module}` namespace;
only these two component files are discoverable. No runtime code is maintained
in this packaging directory. Maintainers regenerate metadata and hook copies
with `python scripts/service_packages.py`, then use `--check` to detect drift.
"""
    return files


def main() -> None:
    """Write generated metadata, or fail if checked-in files have drifted."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in generated_files().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        raise SystemExit("Regenerate service packages: " + ", ".join(stale))


if __name__ == "__main__":
    main()
