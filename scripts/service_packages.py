"""Generate small service packaging projects; runtime source stays in src/."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVICES = {
    "suno": ("suno", "Suno", "Music"),
    "seedance": ("seedance", "Seedance", "Clapperboard"),
    "happyhorse": ("happy_horse", "HappyHorse", "Clapperboard"),
    "gpt-image": ("gpt_image", "GPT Image", "Image"),
    "nano-banana": ("nano_banana", "Nano Banana", "Image"),
}


def generated_files() -> dict[Path, str]:
    """Return reproducible metadata and hook copies for the five projects."""
    version = json.loads((ROOT / "src/lfx_acedatacloud/extension.json").read_text())[
        "version"
    ]
    files = {}
    for slug, (key, label, icon) in SERVICES.items():
        module = f"lfx_acedatacloud_{key}"
        distribution = f"lfx-acedatacloud-{slug}"
        bundle = f"ace_{key}"
        display = f"{label} by Ace Data Cloud"
        directory = ROOT / "packages" / slug
        files[
            directory / "pyproject.toml"
        ] = f'''# Generated by scripts/service_packages.py; edit the generator.
[build-system]
requires = ["hatchling>=1.31,<2"]
build-backend = "hatchling.build"

[project]
name = "{distribution}"
version = "{version}"
description = "{display}: generation and same-task retrieval for Langflow"
readme = "README.md"
requires-python = ">=3.10,<3.15"
license = "MIT"
authors = [{{name = "Ace Data Cloud", email = "dev@acedata.cloud"}}]
keywords = ["langflow", "lfx", "{slug}", "acedatacloud"]
dependencies = ["lfx>=1.12.5,<2", "httpx>=0.24,<1"]

[project.urls]
Homepage = "https://platform.acedata.cloud"
Documentation = "https://github.com/AceDataCloud/LangflowAceDataCloud/blob/main/guides/{slug if slug != "happyhorse" else "happy-horse"}.md"
Repository = "https://github.com/AceDataCloud/LangflowAceDataCloud"

[project.entry-points."langflow.extensions"]
{distribution} = "{module}"

[tool.hatch.service]
key = "{key}"
module = "{module}"
bundle = "{bundle}"
display = "{display}"
icon = "{icon}"

[tool.hatch.build.hooks.custom]
path = "hatch_build.py"

[tool.hatch.build.targets.wheel]
bypass-selection = true
exclude = ["*"]

[tool.hatch.build.targets.sdist]
include = ["/pyproject.toml", "/README.md", "/LICENSE", "/hatch_build.py", "/src"]
'''
        files[directory / "hatch_build.py"] = (
            "# Generated from scripts/service_build_hook.py; do not edit.\n"
            + (ROOT / "scripts/service_build_hook.py").read_text()
        )
        files[directory / "LICENSE"] = (ROOT / "LICENSE").read_text()
        files[directory / "README.md"] = f"""# {display} for Langflow

Install just the {label} Generate and Retrieve Task nodes. This service package
does not install the full Ace bundle or register a chat model provider.
It uses the same reviewed client, request rules, and task implementation as the
aggregate package. Ace Data Cloud supplies this integration; service-owner
endorsement is not implied.

Version {version}. Install in the same Python environment as Langflow:

```bash
python -m pip install "{distribution}=={version}"
lfx extension list
langflow run
```

The [versioned GitHub release](https://github.com/AceDataCloud/LangflowAceDataCloud/releases/tag/v{version}) also provides a wheel and self-contained source archive for this service.

Restart an existing server. Open **Components → {display}** or search **{label}**.
Bind an Ace application API key stored as a Langflow Credential to both nodes.
Generate submits once; Retrieve Task only queries the original task. API usage
is paid according to current service prices; installing this extension is free.
See the [English guide](https://github.com/AceDataCloud/LangflowAceDataCloud/blob/main/guides/{slug if slug != "happyhorse" else "happy-horse"}.md)
and [Chinese guide](https://github.com/AceDataCloud/LangflowAceDataCloud/blob/main/guides/{slug if slug != "happyhorse" else "happy-horse"}_zh_CN.md).


The wheel includes no-key generation and retrieve-only flow JSON under
`{module}/examples/`; use these with this service package. Aggregate examples
retain `ext:ace_data_cloud:*` IDs and require the aggregate installation.
This package uses `ext:{bundle}:<Class>@official` IDs. All five service packages
can coexist. With the aggregate installed, its legacy category remains alongside
the service category; neither replaces the other's saved nodes. Uninstalling
one package does not remove another package's files.

From the complete `v{version}` source checkout, build a wheel and a self-contained sdist with `python -m build packages/{slug}`. A local source install is `python -m pip install ./packages/{slug}`.
The shared hook stages runtime source under the unique `{module}` namespace;
only these two component files are discoverable. No runtime code is maintained
in this packaging directory. Maintainers regenerate metadata and hook copies
with `python scripts/service_packages.py`, then use `--check` to detect drift.
"""
    return files


def main() -> None:
    """Write generated metadata, or fail if checked-in files have drifted."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in generated_files().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        raise SystemExit("Regenerate service packages: " + ", ".join(stale))


if __name__ == "__main__":
    main()
